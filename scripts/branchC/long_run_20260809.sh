#!/usr/bin/env bash
# 2026-08-09 긴 런 — dir 설정으로 30,000 스텝까지 (011 §7)
#
# 🚨 GPU 0 만 쓴다 (CLAUDE.md).
#
# 왜 dir 설정인가
#   G2·G2.5 를 통과한 유일한 팔이다(011 §3). 짝지은 step 4,500 에서 약한 축(지우기)도
#   앞선다 — cos⁻ +0.284 vs +0.276, amp⁻ 0.401 vs 0.329 (011 §4).
#   008 §8-② 가 1순위로 지목한 것도 방향항이다.
#
# 왜 full_005000 에서 시작하나 (7,000 이 아니라)
#   dir 팔의 재개 가능 지점이 그것뿐이다. ck_007000.pt 에는 옵티마이저가 없다.
#   5,000→7,000 을 다시 지나가는 데 2.8시간이 들지만, 옵티마이저를 새로 초기화하면
#   Adam 모멘트가 0 이라 재개 직후 큰 걸음을 밟아 모델을 망가뜨릴 수 있다.
#   (이 낭비를 없애려고 full 저장 주기를 1,000 스텝으로 이미 고쳤다 — 011 §5-③.
#    이 런부터 적용된다.)
#
# 왜 λ_c 를 넘겨주나
#   005 치-7 은 "λ 를 1회 측정해 고정"을 처방했다. 그런데 재개하면 코드가 다시 잰다.
#   이어붙인 런의 손실이 달라지면 같은 런의 연속이 아니게 된다. 원래 값 0.012 로 고정한다.
#
# 왜 주파수 손실을 안 켜나
#   G2.5 조건은 성립했지만 항이 구현돼 있지 않다(009 §4). 그리고 004 §3 이
#   "방향이 틀린 상태에서 선명하게 만들면 틀린 움직임이 더 선명해질 뿐"이라 했는데
#   코사인 0.477 은 방향이 절반만 맞다는 뜻이다. 긴 런 하나에 미검증 항을 얹지 않는다.
#
# 중간에 끊겨도 된다 — full 체크포인트가 1,000 스텝마다 남는다.
# GPU 를 뺏기면 마지막 full_*.pt 에서 같은 명령으로 이어가라 (--lam-c 0.012 를 꼭 같이).
set -u
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO"
PY="$REPO/.venv/bin/python"
CK="${1:-$REPO/artifacts/branchC/train_20260809_0059_dir/full_005000.pt}"
export CUDA_VISIBLE_DEVICES=0

LOG="$REPO/run_logs/$(date +%Y%m%d_%H%M)_train_c_long.log"
echo "════════════════════════════════════════════════════════════"
echo "[$(date +%H:%M:%S)] 긴 런 시작 — GPU $CUDA_VISIBLE_DEVICES"
echo "  재개점: ${CK#$REPO/}"
echo "  로그:   ${LOG#$REPO/}"
echo "  판정:   M3 = step 15,000 (008 §8-③)"
echo "          코사인 ≥0.60 계속 / 0.30~0.60 경계 / <0.30 구조를 바꾼다"
echo "════════════════════════════════════════════════════════════"

"$PY" scripts/branchC/train_c.py \
  --tag long --steps 30000 --resume "$CK" \
  --wake-step 2000 --micro-batch 2 --accum 8 \
  --dir-loss --tau-alpha 0.1 --lam-c 0.012 \
  2>&1 | tee "$LOG"

echo "[$(date +%H:%M:%S)] 긴 런 종료 rc=${PIPESTATUS[0]}"
