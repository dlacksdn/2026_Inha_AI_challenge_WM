def check_g6(scores: list[float]) -> str:
    """G6 — λ 를 낮춰 정지영상을 넘었는가. scores = 그 체크포인트에서 제출한 리더보드 값들."""
    if not scores:
        return "미판정"
    best = min(scores)
    if best < S0_MEASURED - S0_NOISE:
        return "pass"
    if best > S0_MEASURED + S0_NOISE:
        return "fail"
    return "tie"


def check_g7(curve: list[tuple[int, float]]) -> str:
    """G7 — 학습량 곡선. curve = [(step, 리더보드), ...]. **λ 가 전부 같아야 한다.**"""
    pts = sorted(curve)
    if len(pts) < 4:
        return "미판정"
    scores = [s for _, s in pts]
    # 마지막 2점 각각이, 그 앞까지의 최저를 갱신했는가
    renewed = [scores[i] < min(scores[:i]) for i in (len(scores) - 2, len(scores) - 1)]
    if all(renewed):
        return "pass"
    return "tie" if any(renewed) else "fail"


def check_g8(curve: list[tuple[int, float]]) -> str:
    """G8 — 30,000 을 넘겨 45,000 까지 연장할까."""
    pts = sorted(curve)
    if len(pts) < 4:
        return "미판정"
    argmin = min(range(len(pts)), key=lambda i: pts[i][1])
    return "pass" if argmin >= len(pts) - 2 else "fail"


